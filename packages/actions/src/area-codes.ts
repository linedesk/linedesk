const words = (text: string) =>
  text
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean)

/** Does one searched word fit the area code: the start of the code, of a word of the city or state name, or the state's two letters. */
function fits(a: AreaCode, word: string): boolean {
  if (/^\d+$/.test(word)) return a.code.startsWith(word)
  if (word === a.state.toLowerCase()) return true
  return [...words(a.city), ...words(REGION_NAMES[a.state] ?? '')].some(w => w.startsWith(word))
}

/**
 * The area codes that fit every word of the search, in list order: "503", "portland", "OR", "oregon" and
 * "Portland, OR" (a label as shown) all work. All of them while nothing is typed.
 */
export function searchAreaCodes(list: readonly AreaCode[], query: string): AreaCode[] {
  const searched = words(query)
  if (!searched.length) return [...list]
  return list.filter(a => searched.every(w => fits(a, w)))
}
