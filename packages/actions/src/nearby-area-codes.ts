/** "Toronto, ON": the key of an area code's main city in PLACES. */
export const placeOf = (a: AreaCode): string => `${a.city}, ${a.state}`

/** Great-circle distance in km between two [latitude, longitude] points. */
export function distanceKm(a: readonly [number, number], b: readonly [number, number]): number {
  const rad = Math.PI / 180
  const dLat = (b[0] - a[0]) * rad
  const dLon = (b[1] - a[1]) * rad
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a[0] * rad) * Math.cos(b[0] * rad) * Math.sin(dLon / 2) ** 2
  return 2 * 6371 * Math.asin(Math.sqrt(h))
}

/** At most this many codes are suggested (and searched at the carrier) for one empty area code. */
export const NEARBY_LIMIT = 8
/** Codes whose main city is farther than this from the empty code's are not "nearby". */
export const NEARBY_KM = 400

/** A code to try instead of an empty one; `sameArea`: an overlay, numbers of the very same place. */
export type NearbyAreaCode = AreaCode & { sameArea: boolean }

/**
 * The area codes to try when `code` has no free number, best first: its overlays (same main city), then the codes of
 * the same country by distance of their main cities, up to NEARBY_KM away; NEARBY_LIMIT at most. Ties keep code
 * order. Empty for a code that is not in AREA_CODES.
 */
export function nearbyAreaCodes(code: string, limit = NEARBY_LIMIT): NearbyAreaCode[] {
  const from = buyableAreaCode(code)
  if (!from) return []
  const here = PLACES[placeOf(from)]
  const others = BUYABLE_AREA_CODES.filter(a => a.code !== code && a.country === from.country)
  const sameArea = others.filter(a => placeOf(a) === placeOf(from)).map(a => ({ ...a, sameArea: true }))
  const near = here
    ? others
        .filter(a => placeOf(a) !== placeOf(from))
        .map(a => ({ a, km: PLACES[placeOf(a)] ? distanceKm(here, PLACES[placeOf(a)]!) : Infinity }))
        .filter(n => n.km <= NEARBY_KM)
        .sort((x, y) => x.km - y.km || x.a.code.localeCompare(y.a.code))
        .map(n => ({ ...n.a, sameArea: false }))
    : []
  return [...sameArea, ...near].slice(0, limit)
}
