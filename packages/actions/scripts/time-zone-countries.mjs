// Writes src/time-zone-countries.ts: the country of each IANA time zone, from the tz database's zone.tab (one country
// per zone) and its links (old names such as US/Eastern or Asia/Calcutta, the country of the zone they point to).
// Run when the tz database changes: node packages/actions/scripts/time-zone-countries.mjs [zoneinfo directory]
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const dir = process.argv[2] ?? '/usr/share/zoneinfo'
const rows = line => line.trim() && !line.startsWith('#')
const zones = new Map()
for (const line of readFileSync(`${dir}/zone.tab`, 'utf8').split('\n').filter(rows)) {
  const [country, , zone] = line.split('\t')
  zones.set(zone, country)
}
const linksFile = `${dir}/tzdata.zi`
if (existsSync(linksFile))
  for (const line of readFileSync(linksFile, 'utf8').split('\n')) {
    const [kind, target, alias] = line.split(' ')
    if (kind === 'L' && !zones.has(alias) && zones.has(target)) zones.set(alias, zones.get(target))
  }
const byCountry = new Map()
for (const [zone, country] of [...zones].sort(([a], [b]) => a.localeCompare(b)))
  byCountry.set(country, [...(byCountry.get(country) ?? []), zone])
const version = existsSync(linksFile) ? readFileSync(linksFile, 'utf8').split('\n')[0].replace('# version ', '') : '?'
const body = [...byCountry]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([country, list]) => `  ${country}: '${list.join(' ')}',`)
  .join('\n')
writeFileSync(
  new URL('../src/time-zone-countries.ts', import.meta.url),
  `// Generated by scripts/time-zone-countries.mjs from the tz database (${version}); do not edit.
// The IANA time zones of each country (ISO 3166-1 alpha-2), old link names included.
export const TIME_ZONES_BY_COUNTRY: Readonly<Record<string, string>> = {
${body}
}
`,
)
console.log(`${zones.size} zones, ${byCountry.size} countries`)
