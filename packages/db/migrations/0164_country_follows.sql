UPDATE "workspace_settings" ws SET
  "job_value_currency_follows_country" = ws."job_value_cents" IS NULL OR EXISTS (
    SELECT 1 FROM country_currencies cc
    WHERE cc.country = coalesce(ws."country", ws."country_hint") AND cc.currency = ws."job_value_currency"::text
  ),
  "job_value_currency" = CASE WHEN ws."job_value_cents" IS NULL THEN coalesce(
    (SELECT cc.currency FROM country_currencies cc WHERE cc.country = coalesce(ws."country", ws."country_hint")),
    ws."job_value_currency"::text
  ) ELSE ws."job_value_currency"::text END;
